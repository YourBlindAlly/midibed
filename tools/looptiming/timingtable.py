import os, re, subprocess, sys, json
import numpy as np

ROOT = r"C:\Users\rusty\OneDrive\Documents\claude code folder\drone percussion app\loops"
FOLDERS = ["SHAKERZ flat FLAC 16 bit", "TAMBOREENE flat FLAC 16 bit", "shake Loops flat FLAC 16 bit",
           "Pete Locket - All loops flat FLAC 16 bit", "Shell loops flat FLAC 16 bit"]
SR = 22050


def load(path):
    cmd = ["ffmpeg", "-v", "error", "-i", path, "-ac", "1", "-ar", str(SR), "-f", "f32le", "-"]
    return np.frombuffer(subprocess.run(cmd, capture_output=True).stdout, dtype=np.float32)


def tempo_of(name):
    m = re.findall(r"(?<![0-9])([0-9]{2,3})\s*bpm", name, re.I)
    if m:
        return float(m[-1])
    m = [float(x) for x in re.findall(r"[_\- ]([0-9]{2,3})(?=[_\-. ]|$)", name) if 40 <= float(x) <= 220]
    return m[-1] if m else None


def onset_times(x):
    y = np.diff(x, prepend=0)
    w = int(0.003 * SR)
    e = np.sqrt(np.convolve(y * y, np.ones(w) / w, mode="same"))
    le = np.log(e + 1e-5)
    k = int(0.006 * SR)
    rise = np.zeros_like(le)
    rise[k:] = le[k:] - le[:-k]
    mx = rise.max()
    thr = max(1.0, 0.45 * mx)
    gap = int(0.05 * SR)
    out, last = [], -10 ** 9
    for i in range(1, len(rise) - 1):
        if rise[i] >= thr and rise[i] >= rise[i - 1] and rise[i] >= rise[i + 1] and i - last > gap:
            out.append(i / SR)
            last = i
    return np.array(out)


def key(name):
    n = re.sub(r"\.(wav|flac|aif|aiff|mp3|m4a|caf)$", "", name, flags=re.I)
    return re.sub(r"[^a-z0-9]", "", n.lower())


table = {}
report = []
for fd in FOLDERS:
    d = os.path.join(ROOT, fd)
    for f in sorted(os.listdir(d)):
        T = tempo_of(f)
        if T is None or not (40 <= T <= 220):
            continue
        x = load(os.path.join(d, f))
        dur = len(x) / SR
        if dur > 12 or dur < 0.8:
            continue
        on = onset_times(x)
        if len(on) < 4:
            continue
        step = 60.0 / T / 4
        dev = (on - np.round(on / step) * step) * 1000
        med = float(np.median(dev))
        spread = float(np.median(np.abs(dev - med))) * 1.4826
        half = step * 1000 / 2
        use = spread <= 30 and abs(med) >= 8 and abs(med) <= min(80, half * 0.9)
        report.append((f, T, round(med, 1), round(spread, 1), use))
        if use:
            table[key(f)] = int(round(-med))

with open(sys.argv[1], "w", encoding="utf-8") as fh:
    fh.write("// Generated by the timing scan (see tools/looptiming/README.md). Do not edit by hand.\n")
    fh.write("// Milliseconds to move a loop so its hits land on the beat: positive = later, negative = earlier.\n")
    fh.write("// Key = the loop's file name, lower case, without the extension and with every other character removed.\n")
    fh.write("export const LOOP_TIMING: Record<string, number> = {\n")
    for k in sorted(table):
        fh.write(f"  {k}: {table[k]},\n")
    fh.write("};\n")
print(len(report), "scanned;", len(table), "get a nudge")
json.dump(report, open(sys.argv[1] + ".report.json", "w"))
